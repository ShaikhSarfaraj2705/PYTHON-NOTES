# =====================================================
# URL ROUTING IN DJANGO
# =====================================================

# URL Routing is the process of mapping a URL (web address)
# to a specific view (Python function or class).

# Example:
# URL                    View
# -----------------------------------
# /                      home()
# /about/                about()
# /contact/              contact()

# Django checks the URL entered by the user
# and executes the matching view.