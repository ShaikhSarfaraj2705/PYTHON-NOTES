# Authentication
# ----------------
# Authentication verifies the identity of a user.
#
# Example:
# Username + Password
#
# Questions answered:
# "Who are you?"

# Authorization
# ----------------
# Authorization determines what an authenticated
# user is allowed to do.
#
# Example:
# Admin can delete records.
# Normal users can only view records.
#
# Questions answered:
# "What are you allowed to do?"

# Django provides a built-in authentication system.