# =====================================================
# FUNCTION-BASED VIEWS (FBV)
# =====================================================

# A Function-Based View (FBV) is a normal Python function
# that accepts an HTTP request and returns an HTTP response.

# Syntax:
#
# def view_name(request):
#     return HttpResponse("Response")

# Advantages:
# 1. Easy to learn
# 2. Simple to write
# 3. Best for small applications
# 4. Easy to understand