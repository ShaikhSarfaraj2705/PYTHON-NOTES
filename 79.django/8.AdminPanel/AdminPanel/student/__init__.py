# =====================================================
# DJANGO ADMIN PANEL
# =====================================================

# Django provides a built-in Admin Panel
# to manage application data without writing
# CRUD (Create, Read, Update, Delete) code.

# Features:
# 1. Add Records
# 2. Update Records
# 3. Delete Records
# 4. Search Records
# 5. Filter Records
# 6. Manage Users and Groups

# Default Admin URL
# http://127.0.0.1:8000/admin/

# CREATE ADMIN USER
# python manage.py createsuperuser


# Change Password of Superuser
# python manage.py changepassword admin


# Open Django Shell
# python manage.py shell